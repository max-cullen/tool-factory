// Build one tool site.  Usage: node framework/build.mjs <tool-folder-name> [--preview]
// Output: tools/<tool>/dist  (plain static files: upload that folder to any static host)
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createContext, layout, adsTxt, faviconSvg } from './lib.mjs';

const FRAMEWORK = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(FRAMEWORK, '..');
const toolName = process.argv.slice(2).find((a) => !a.startsWith('-'));
const preview = process.argv.includes('--preview');
if (!toolName) {
  console.error('Usage: node framework/build.mjs <tool> [--preview]   (tools: ' + fs.readdirSync(path.join(ROOT, 'tools')).filter((d) => !d.startsWith('_')).join(', ') + ')');
  process.exit(1);
}
const TOOL = path.join(ROOT, 'tools', toolName);
const DIST = path.join(TOOL, 'dist');
if (!fs.existsSync(path.join(TOOL, 'site.mjs'))) { console.error(`No tools/${toolName}/site.mjs`); process.exit(1); }

// Fonts: embedded so the site has no third-party requests. Plus Jakarta Sans, SIL Open Font License.
const fontFile = path.join(ROOT, 'node_modules/@fontsource-variable/plus-jakarta-sans/files/plus-jakarta-sans-latin-wght-normal.woff2');
fs.writeFileSync(path.join(FRAMEWORK, 'fonts.css'), `/* generated by framework/build.mjs: Plus Jakarta Sans (SIL OFL 1.1), latin subset, embedded */
@font-face{font-family:"Plus Jakarta Sans Variable";font-style:normal;font-display:swap;font-weight:200 800;src:url(data:font/woff2;base64,${fs.readFileSync(fontFile).toString('base64')}) format("woff2-variations")}
`);

const network = JSON.parse(fs.readFileSync(path.join(ROOT, 'network.json'), 'utf8'));
const { default: def } = await import(pathToFileURL(path.join(TOOL, 'site.mjs')).href);
const ctx = createContext({ site: def.site, pages: def.pages, network, preview });

fs.rmSync(DIST, { recursive: true, force: true });
fs.mkdirSync(path.join(DIST, 'assets'), { recursive: true });
fs.copyFileSync(path.join(FRAMEWORK, 'site.js'), path.join(DIST, 'assets/site.js'));
for (const [from, to] of def.copy || []) {
  const dest = path.join(DIST, to);
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.copyFileSync(path.join(TOOL, from), dest);
}

const indexable = [];
for (const page of def.pages) {
  const out = page.render(ctx, page);
  const html = layout(ctx, page, out);
  const file = page.slug ? path.join(DIST, page.slug, 'index.html') : path.join(DIST, 'index.html');
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, html);
  if (!out.noindex) indexable.push(page);
}
const base = def.site.url.replace(/\/$/, '');
fs.writeFileSync(path.join(DIST, 'sitemap.xml'), `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${indexable.map((p) => `  <url><loc>${base}/${p.slug ? p.slug + '/' : ''}</loc></url>`).join('\n')}\n</urlset>\n`);
fs.writeFileSync(path.join(DIST, 'favicon.svg'), faviconSvg(def.site));
// PNG/ICO icons are made once per tool with `python3 framework/make_icons.py <tool>` and kept in tools/<tool>/icons/.
for (const f of ['favicon.ico', 'apple-touch-icon.png', 'icon-512.png']) {
  const src = path.join(TOOL, 'icons', f);
  if (fs.existsSync(src)) fs.copyFileSync(src, path.join(DIST, f));
}
const ads = adsTxt(def.site);
if (ads) fs.writeFileSync(path.join(DIST, 'ads.txt'), ads);
fs.writeFileSync(path.join(DIST, 'robots.txt'), preview ? 'User-agent: *\nDisallow: /\n' : `User-agent: *\nAllow: /\nSitemap: ${base}/sitemap.xml\n`);

execFileSync(path.join(ROOT, 'node_modules/.bin/tailwindcss'), ['-i', path.join(TOOL, 'styles.css'), '-o', path.join(DIST, 'assets/styles.css'), '--minify'], { cwd: ROOT, stdio: ['ignore', 'ignore', 'inherit'] });

// Tools served inside this site at a sub-path (e.g. FitReel at usefitpic.com/instagram/): build each one and copy
// its dist into ours. Its pages join our sitemap; robots.txt and ads.txt only make sense at the domain root.
for (const inc of def.include || []) {
  execFileSync(process.execPath, [fileURLToPath(import.meta.url), inc.tool, ...(preview ? ['--preview'] : [])], { stdio: 'inherit' });
  const from = path.join(ROOT, 'tools', inc.tool, 'dist');
  const to = path.join(DIST, inc.path);
  fs.cpSync(from, to, { recursive: true });
  for (const f of ['robots.txt', 'ads.txt']) fs.rmSync(path.join(to, f), { force: true });
  const subMap = path.join(to, 'sitemap.xml');
  const urls = fs.readFileSync(subMap, 'utf8').match(/<url>.*?<\/url>/g) || [];
  fs.rmSync(subMap);
  const mainMap = path.join(DIST, 'sitemap.xml');
  fs.writeFileSync(mainMap, fs.readFileSync(mainMap, 'utf8').replace('</urlset>', urls.map((u) => `  ${u}\n`).join('') + '</urlset>'));
}
console.log(`built ${toolName}: ${def.pages.length} pages${preview ? ' (preview)' : ''} -> ${path.relative(ROOT, DIST)}`);
